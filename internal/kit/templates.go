const pyMiddleware = `# Generated by Deskweaver. Review-only template; it is not applied.
# Loopback token, Origin, Host, and content-length checks for a local Python API.
import hmac
import os


class LocalAPIGuard:
    def __init__(self, app, token: str, allowed_hosts=("127.0.0.1", "localhost", "[::1]")):
        if not token or len(token) < 32:
            raise ValueError("use a per-launch token with at least 32 characters")
        self.app = app
        self.token = token
        self.allowed_hosts = set(allowed_hosts)
        self.max_body = 10 * 1024 * 1024

    def __call__(self, environ, start_response):
        host = (environ.get("HTTP_HOST") or "").split(":")[0]
        origin = environ.get("HTTP_ORIGIN") or ""
        supplied = environ.get("HTTP_X_DESKWEAVER_TOKEN") or ""
        if host not in self.allowed_hosts:
            return self._deny(start_response, "bad host")
        if origin and origin not in {"http://127.0.0.1", "http://localhost", "http://[::1]"}:
            return self._deny(start_response, "bad origin")
        if not hmac.compare_digest(supplied, self.token):
            return self._deny(start_response, "bad token")
        try:
            length = int(environ.get("CONTENT_LENGTH") or 0)
        except ValueError:
            return self._deny(start_response, "bad content length")
        if length > self.max_body:
            return self._deny(start_response, "body too large")
        return self.app(environ, start_response)

    @staticmethod
    def _deny(start_response, reason):
        body = ('{"error":"' + reason + '"}').encode("utf-8")
        start_response("403 Forbidden", [
            ("Content-Type", "application/json"),
            ("Content-Length", str(len(body))),
            ("Cache-Control", "no-store"),
        ])
        return [body]


def token_from_env():
    token = os.environ.get("DESKWEAVER_LOCAL_TOKEN", "")
    if len(token) < 32:
        raise RuntimeError("DESKWEAVER_LOCAL_TOKEN is missing or too short")
    return token
`

const tsMiddleware = `// Generated by Deskweaver. Review-only template; it is not applied.
// Express-style loopback token/origin guard for a local Node API.
import { timingSafeEqual } from "node:crypto";
import type { RequestHandler } from "express";

const MAX_BODY = 10 * 1024 * 1024;
const allowedOrigins = new Set(["http://127.0.0.1", "http://localhost", "http://[::1]"]);

export function localApiGuard(token: string): RequestHandler {
  if (token.length < 32) throw new Error("use a per-launch token with at least 32 characters");
  const expected = Buffer.from(token, "utf8");
  return (req, res, next) => {
    const host = (req.headers.host ?? "").split(":")[0];
    if (!["127.0.0.1", "localhost", "[::1]"].includes(host)) {
      res.status(403).json({ error: "bad host" });
      return;
    }
    const origin = req.headers.origin;
    if (origin && !allowedOrigins.has(origin)) {
      res.status(403).json({ error: "bad origin" });
      return;
    }
    const supplied = Buffer.from(String(req.headers["x-deskweaver-token"] ?? ""), "utf8");
    if (supplied.length !== expected.length || !timingSafeEqual(supplied, expected)) {
      res.status(403).json({ error: "bad token" });
      return;
    }
    const length = Number(req.headers["content-length"] ?? 0);
    if (!Number.isFinite(length) || length > MAX_BODY) {
      res.status(413).json({ error: "body too large" });
      return;
    }
    next();
  };
}
`

