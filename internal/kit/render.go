func renderRollback(plan model.Plan) string {
	var b strings.Builder
	b.WriteString("# Rollback and safety notes\n\n")
	b.WriteString("> Generated by Deskweaver. No rollback command is executed by this kit.\n\n")
	b.WriteString("## What the generator does\n\n")
	b.WriteString("- Renders every file in a hidden staging directory next to the output path.\n")
	b.WriteString("- Commits the directory with a single rename, which is atomic on the same filesystem.\n")
	b.WriteString("- If the output directory already exists and is non-empty, `--force` moves it to a timestamped `.backup-` directory instead of deleting it.\n")
	b.WriteString("- If generation fails before commit, the staging directory is removed and the existing output is untouched.\n\n")
	b.WriteString("## What it never does\n\n")
	b.WriteString("- It never writes into the scanned project.\n")
	b.WriteString("- It never executes generated scripts, package managers, build tools, or project code.\n")
	b.WriteString("- It never invokes an elevation tool.\n")
	b.WriteString("- It never deletes a non-empty output directory.\n\n")
	b.WriteString("## Manual recovery\n\n")
	b.WriteString("If you used `--force`, the previous directory remains beside the output path with a `.backup-` suffix. Inspect it, then move it back into place yourself after stopping any process that uses the kit. Do not copy a backup over a live project without a diff and a second review.\n\n")
	if plan.ArtifactManifest != "" {
		fmt.Fprintf(&b, "Verify the current kit with `sha256sum -c %s` after review. The manifest does not include itself.\n", plan.ArtifactManifest)
	}
	return b.String()
}

