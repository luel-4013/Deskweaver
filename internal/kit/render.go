func renderCSP(plan model.Plan) string {
	server := hasServer(plan)
	connect := "'self'"
	if server {
		connect = "'self' http://127.0.0.1:* http://[::1]:* ws://127.0.0.1:*"
	}
	worker := ""
	if plan.Recommendation.Primary != nil && plan.Recommendation.Primary.ID == "pwa" {
		worker = " worker-src 'self';"
	}
	return "default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' data:; font-src 'self'; connect-src " + connect + ";" + worker + " object-src 'none'; base-uri 'none'; frame-ancestors 'none'; form-action 'self'; upgrade-insecure-requests\n"
}

