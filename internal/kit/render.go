func renderReadme(plan model.Plan) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Deskweaver review kit: %s\n\n", mdText(plan.Project.Name))
	b.WriteString("> Generated by Deskweaver. **Review-only.** No generated script was executed, no dependency was installed, and no project file was modified.\n\n")
	fmt.Fprintf(&b, "- Plan hash: `%s`\n", plan.PlanHash)
	fmt.Fprintf(&b, "- Generated at: `%s`\n", plan.GeneratedAt)
	fmt.Fprintf(&b, "- Tool: `%s`, rules `%s` (`%s`)\n", plan.ToolVersion, plan.RulesVersion, plan.RulesHash)
	if plan.ArtifactManifest != "" {
		fmt.Fprintf(&b, "- Checksums: `%s`\n", plan.ArtifactManifest)
	}
	b.WriteString("\n## Start here\n\n")
	b.WriteString("1. Read `plan.md` end to end.\n")
	b.WriteString("2. Read `security/SECURITY.md` and the controls in `security/controls.yaml`.\n")
	b.WriteString("3. Check `answers.yaml` against your intent; re-run with `--answers` to reproduce the decision set.\n")
	if CanConvert(plan.Recommendation) {
		b.WriteString("4. Review `conversion/README.md`, then run `conversion/preflight.sh` (read-only).\n")
		b.WriteString("5. Review every template in `security/` before copying anything into a real project.\n")
	} else {
		b.WriteString("4. This plan has no conversion kit. Read the blockers before creating one.\n")
	}
	b.WriteString("\n## Ground rules\n\n")
	b.WriteString("- Nothing here is applied automatically.\n")
	b.WriteString("- The preflight script only checks for tools; it installs nothing and writes nothing.\n")
	b.WriteString("- Commands in `conversion/commands.txt` are illustrative; run them only after review.\n")
	b.WriteString("- Keep the generated kit out of the scanned project unless you explicitly chose an output there.\n")
	b.WriteString("\n## Limitations\n\n")
	b.WriteString("- Deskweaver is an advisor, not a build system, packager, or security certification.\n")
	b.WriteString("- Support levels are engineering judgments, not vendor guarantees.\n")
	b.WriteString("- Re-scan after dependency upgrades; stale advice is a risk in itself.\n")
	return b.String()
}

func renderPlan(plan model.Plan) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Deskweaver plan: %s\n\n", mdText(plan.Project.Name))
	b.WriteString("> Generated by Deskweaver. Review-only: nothing in this document was executed or applied.\n\n")

	b.WriteString("## Verdict\n\n")
	if plan.Recommendation.Primary == nil {
		b.WriteString("**No automatic recommendation.** Manual review is required.\n\n")
	} else {
		fmt.Fprintf(&b, "**Primary:** %s (score %d/100)  \n", mdText(plan.Recommendation.Primary.Name), plan.Recommendation.Primary.Score)
		if plan.Recommendation.Fallback != nil {
			fmt.Fprintf(&b, "**Fallback:** %s (score %d/100)  \n", mdText(plan.Recommendation.Fallback.Name), plan.Recommendation.Fallback.Score)
		}
		fmt.Fprintf(&b, "**Targets:** %s  \n", mdText(strings.Join(plan.Recommendation.RequestedTargets, ", ")))
		fmt.Fprintf(&b, "**Architecture:** %s  \n", mdText(plan.Recommendation.Architecture))
		fmt.Fprintf(&b, "**Sensitivity:** %s  \n", mdText(plan.Recommendation.Sensitivity))
	}
	fmt.Fprintf(&b, "**Plan hash:** `%s`\n\n", plan.PlanHash)

	b.WriteString("| Field | Value |\n|---|---|\n")
	row := func(k, v string) { fmt.Fprintf(&b, "| %s | %s |\n", mdCell(k), mdCell(v)) }
	row("Project root", plan.Project.Root)
	row("Project schema", plan.Project.Schema)
	row("Files scanned", fmt.Sprint(plan.Project.ScannedFiles))
	row("Files skipped", fmt.Sprint(plan.Project.SkippedFiles))
	row("Monorepo", yesNo(plan.Project.Monorepo))
	row("Workspace", firstNonEmpty(plan.Answers.Workspace, "(root)"))
	row("Security profile", plan.Security.Profile)
	row("Network model", plan.Security.ThreatModel.Network)
	row("Privilege", plan.Security.ThreatModel.Privilege)
	row("Kit generated", yesNo(plan.Answers.GenerateKit))
	b.WriteString("\n")

	b.WriteString("## Detected stack\n\n")
	if plan.Project.Primary == nil {
		b.WriteString("No framework matched with enough evidence. Treat the project profile as unknown and complete a manual review.\n\n")
	} else {
		p := plan.Project.Primary
		fmt.Fprintf(&b, "**Primary:** %s (Tier %s, %s confidence, score %d/100)\n\n", mdText(p.Name), p.Tier, p.Confidence, p.Score)
		if p.Version != "" {
			fmt.Fprintf(&b, "Detected version: `%s`\n\n", mdText(p.Version))
		}
		b.WriteString("| Detection | Tier | Confidence | Score | Language |\n|---|---|---|---|---|\n")
		for _, d := range plan.Project.Detections {
			fmt.Fprintf(&b, "| %s | %s | %s | %d | %s |\n", mdCell(d.Name), d.Tier, d.Confidence, d.Score, mdCell(d.Language))
		}
		b.WriteString("\n**Evidence**\n\n")
		for _, ev := range p.Evidence {
			fmt.Fprintf(&b, "- `%s` %s — %s\n", mdText(ev.Path), mdText(ev.Kind), mdText(ev.Detail))
		}
		b.WriteString("\n")
	}

	b.WriteString("## OS support matrix\n\n")
	b.WriteString("Levels: S0 unsupported, S1 experimental, S2 works with caveats, S3 supported/tested, S4 hardened/distribution-ready. These are technical judgments, not vendor guarantees.\n\n")
	b.WriteString("| OS | Level | Requested | Formats | Notes |\n|---|---|---|---|---|\n")
	for _, s := range plan.Recommendation.OSMatrix {
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n",
			mdCell(title(s.OS)), mdCell(s.Label), yesNo(containsFold(plan.Recommendation.RequestedTargets, s.OS)),
			mdCell(strings.Join(s.Formats, ", ")), mdCell(s.Notes))
	}
	b.WriteString("\n")

	b.WriteString("## Why this recommendation\n\n")
	for _, reason := range plan.Recommendation.Reasons {
		fmt.Fprintf(&b, "- %s\n", mdText(reason))
	}
	b.WriteString("\n")
	if len(plan.Recommendation.Tradeoffs) > 0 {
		b.WriteString("### Trade-offs and explicit risks\n\n")
		for _, t := range plan.Recommendation.Tradeoffs {
			fmt.Fprintf(&b, "- %s\n", mdText(t))
		}
		b.WriteString("\n")
	}
	if len(plan.Recommendation.Rejected) > 0 {
		b.WriteString("### Alternatives considered and rejected\n\n")
		for _, r := range plan.Recommendation.Rejected {
			fmt.Fprintf(&b, "- **%s** (score %d): %s\n", mdText(r.Name), r.Score, mdText(r.Reason))
		}
		b.WriteString("\n")
	}

	b.WriteString("## Threat model\n\n")
	b.WriteString("| Question | Answer |\n|---|---|\n")
	row2 := func(k, v string) { fmt.Fprintf(&b, "| %s | %s |\n", mdCell(k), mdCell(v)) }
	row2("Data sensitivity", plan.Security.ThreatModel.Sensitivity)
	row2("Untrusted input", yesNo(plan.Security.ThreatModel.UntrustedInput))
	row2("Network", plan.Security.ThreatModel.Network)
	row2("Privilege", plan.Security.ThreatModel.Privilege)
	row2("Profile", plan.Security.Profile)
	b.WriteString("\n")

	b.WriteString("## Security controls\n\n")
	b.WriteString(security.Summary(plan.Security) + "\n\n")
	b.WriteString("| ID | Status | Control | Detail |\n|---|---|---|---|\n")
	for _, c := range plan.Security.Controls {
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", mdCell(c.ID), mdCell(c.Status), mdCell(c.Name), mdCell(c.Detail))
	}
	b.WriteString("\n### Residual risks\n\n")
	for _, r := range plan.Security.ResidualRisks {
		fmt.Fprintf(&b, "- %s\n", mdText(r))
	}
	b.WriteString("\n")

	if len(plan.Recommendation.Blockers) > 0 || len(plan.Project.Unknowns) > 0 {
		b.WriteString("## Blockers and unknowns\n\n")
		for _, x := range plan.Recommendation.Blockers {
			fmt.Fprintf(&b, "- **Blocker:** %s\n", mdText(x))
		}
		for _, x := range plan.Project.Unknowns {
			fmt.Fprintf(&b, "- **Unknown:** %s\n", mdText(x))
		}
		b.WriteString("\n")
	}

	b.WriteString("## Host readiness\n\n")
	if len(plan.Host.Tools) == 0 {
		b.WriteString("No host dependencies were probed.\n\n")
	} else {
		b.WriteString("| Tool | Found | Version | Required | Detail |\n|---|---|---|---|---|\n")
		for _, t := range plan.Host.Tools {
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n", mdCell(t.Name), yesNo(t.Found), mdCell(t.Version), yesNo(t.Required), mdCell(t.Detail))
		}
		b.WriteString("\n")
	}
	if len(plan.Host.Checks) > 0 {
		b.WriteString("### Checks and remediation\n\n")
		for _, c := range plan.Host.Checks {
			fmt.Fprintf(&b, "- **%s** [%s]: %s", mdText(c.Name), mdText(c.Status), mdText(c.Detail))
			if c.Install != "" {
				fmt.Fprintf(&b, "  \n  Install guidance (review before running): `%s`", mdText(c.Install))
			}
			if c.Verify != "" {
				fmt.Fprintf(&b, "  \n  Verify: `%s`", mdText(c.Verify))
			}
			b.WriteString("\n")
		}
		b.WriteString("\n")
	}
	if len(plan.Host.Warnings) > 0 {
		b.WriteString("### Host warnings\n\n")
		for _, w := range plan.Host.Warnings {
			fmt.Fprintf(&b, "- %s\n", mdText(w))
		}
		b.WriteString("\n")
	}

	b.WriteString("## Conversion outline\n\n")
	if CanConvert(plan.Recommendation) {
		for i, step := range conversionSteps(plan) {
			fmt.Fprintf(&b, "%d. %s\n", i+1, step)
		}
		b.WriteString("\nThe full review package is in `conversion/`. Nothing is applied automatically.\n\n")
	} else {
		b.WriteString("No conversion steps are generated. The recommendation contains blockers or has no desktop conversion path. Resolve them and re-run Deskweaver.\n\n")
	}

	b.WriteString("## Artifacts\n\n")
	if len(plan.Artifacts) == 0 {
		b.WriteString("No kit was generated.\n")
	} else {
		for _, a := range plan.Artifacts {
			fmt.Fprintf(&b, "- `%s`\n", mdText(a))
		}
	}
	b.WriteString("\n## Method and limitations\n\n")
	b.WriteString("- Detection uses declarative rules with recorded evidence; it does not execute project code.\n")
	b.WriteString("- The recommendation is a weighted engineering judgment over security, feature fit, platform support, effort, maintenance, and size.\n")
	b.WriteString("- EOL/version data is not fetched in this build; verify framework and runtime support before release.\n")
	b.WriteString("- A reviewed configuration that was not tested on the target OS may fail open. Treat the checklist as work, not proof.\n")
	return b.String()
}

