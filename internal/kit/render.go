func renderPreflight(plan model.Plan) string {
	var b strings.Builder
	b.WriteString("#!/bin/sh\n")
	b.WriteString("# Generated by Deskweaver. Read-only preflight check.\n")
	b.WriteString("# It installs nothing, elevates nothing, writes nothing, and runs no project code.\n")
	b.WriteString("set -eu\n")
	b.WriteString("missing=0\n")
	b.WriteString("ok() { printf 'ok      %s\\n' \"$1\"; }\n")
	b.WriteString("bad() { printf 'missing %s\\n' \"$1\"; missing=$((missing + 1)); }\n")
	b.WriteString("check_cmd() {\n  name=$1\n  if command -v \"$name\" >/dev/null 2>&1; then ok \"$name\"; else bad \"$name\"; fi\n}\n")
	b.WriteString("check_pkg() {\n  name=$1\n  if command -v pkg-config >/dev/null 2>&1 && pkg-config --exists \"$name\"; then ok \"pkg-config:$name\"; else bad \"pkg-config:$name\"; fi\n}\n\n")
	b.WriteString("# Review-only: the only accepted argument is --dry-run (the default behavior).\n")
	b.WriteString("for arg in \"$@\"; do\n  case \"$arg\" in\n    --dry-run|--help) ;;\n    *) printf 'unknown argument: %s\\n' \"$arg\"; exit 2 ;;\n  esac\ndone\n\n")
	if plan.Recommendation.Primary != nil {
		if c, ok := recommend.ByID(plan.Recommendation.Primary.ID); ok && len(c.Requires) > 0 {
			b.WriteString("# Requirements declared by the recommendation.\n")
			for _, req := range c.Requires {
				if !safeShellWord(req) {
					continue
				}
				if strings.HasPrefix(req, "webkit2gtk") {
					fmt.Fprintf(&b, "check_pkg %s\n", shQuote(req))
				} else {
					fmt.Fprintf(&b, "check_cmd %s\n", shQuote(req))
				}
			}
			b.WriteString("\n")
		}
	}
	b.WriteString("if [ \"$missing\" -ne 0 ]; then\n  printf '%d dependency check(s) failed. Review install guidance in plan.md; nothing was installed.\\n' \"$missing\"\n  exit 1\nfi\n")
	b.WriteString("printf 'preflight passed. Nothing was installed or written.\\n'\n")
	return b.String()
}

